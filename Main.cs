    // --- world drawing (2.5D) -------------------------------------------------
    // The rules stay flat 2D (GameSim.cs). Only the look is 2.5D: ground first, then everything with
    // height (trees, rocks, walls, enemies, players) sorted by the y of its foot, back to front,
    // so nearer things cover farther ones. Walls are drawn with a top face and a front face.
    public override void _Draw()
    {
        if (!(Gd.Contains(new GArray("day", "dusk", "night", "result"), Gd.Get(Snap, "ph", ""))))
        {
            return;
        }
        dynamic Font = Gd.Wrap(ThemeDB.FallbackFont);
        dynamic VisibleSize = (Gd.Native(this, "get_viewport_rect").Size / Cam.Zoom);
        dynamic View = Gd.MakeRect2((Cam.Position - (VisibleSize / 2)), VisibleSize).Grow((8 * T));
        dynamic H = GameSim.HALF;
        // ground layer: flat, nothing here hides anything
        // the island from the level-design map: sea, shallows, beach, grass, safe zone, woods and hills; then the
        // swamp, routes, trails, door roads and the pond (src/world/view/Main.TerrainView.cs)
        this.DrawIsland((Rect2)View);
        this.DrawTerrain((Rect2)View);
        // grass tufts and pebbles: thousands on the island, so a typed copy is checked against the view
        if (ScatterTyped == null || ScatterTyped.Length != Gd.Size(Scatter))
        {
            ScatterTyped = new (Vector2, string)[Gd.Size(Scatter)];
            for (int I = 0; I < ScatterTyped.Length; I++) ScatterTyped[I] = ((Vector2)Gd.At(Gd.At(Scatter, I), 0), Gd.Str(Gd.At(Gd.At(Scatter, I), 1)));
        }
        Rect2 SeenRect = (Rect2)View;
        Color ColdTyped = (Color)COLD;
        foreach (var (Sp, Sn) in ScatterTyped)
        {
            if (SeenRect.HasPoint(Sp))
            {
                this.Sprite(Sn, Sp, 1.0f, ColdTyped);
            }
        }
        foreach (dynamic I in Gd.Iter(3))
        {
            dynamic Pp = GameSim.PadPos(I);
            this.DrawProp("pad", Pp);
            if (((Snap.K == 5) && (Snap.Ph == "night")))
            {
                dynamic Blink = (0.5f + (0.5f * Gd.Sin((Gd.Static(typeof(Time), "get_ticks_msec") / 200.0f))));
                foreach (dynamic J in Gd.Iter(8))
                {
                    Gd.Native(this, "draw_rect", Gd.MakeRect2(((Pp + (Vector2.FromAngle(((J * Mathf.Tau) / 8.0f)) * 117.0f)) - Gd.MakeVector2(2, 2)), Gd.MakeVector2(4, 4)), (Gd.MakeColor(0.5f, 1.2f, 2.6f) * (0.6f + Blink)));
