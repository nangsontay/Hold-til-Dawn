    public dynamic Bump(dynamic Pos, dynamic R)
    {
        // Keeps the local player's feet out of trees, rocks, the lighthouse and workbench, resource nodes
        // (not herbs), towers and enemies; it slides around them. Walls come after this, so a wall always wins.
        Pos = Geometry.Resolve(Pos, R);
        foreach (dynamic E in Gd.Iter(Gd.Get(Snap, "en", new GArray())))
        {
            Pos = Main.Push(Pos, R, Gd.Get(ShownE, Gd.At(E, 0), Gd.At(E, 2)), (Gd.At(E, 5) * ENEMY_BODY));
        }
        return Pos;
    }

    public static dynamic Push(dynamic Pos, dynamic R, dynamic C, dynamic Cr)
    {
        dynamic D = (Pos - C);
        dynamic Need = (R + Cr);
        if ((D.LengthSquared() >= (Need * Need)))
        {
            return Pos;
        }
        return (C + (((Gd.Length(D) > 0.01f) ? (dynamic)(D.Normalized()) : Vector2.Down) * Need));
    }

