    {
        return (Gd.Truth(Gd.Static(typeof(Input), "is_physical_key_pressed", K)) ? (dynamic)(1.0f) : 0.0f);
    }

    public dynamic DoorsOpen()
    {
        bool Night = Gd.Truth((Gd.Get(Snap, "ph", "") == "night"));
        return Gd.Map(Snap.Doors, (Func<dynamic, dynamic>)((D) => (!(Gd.Truth(Night)) || (D <= 0))));
    }

    public dynamic Breach()
    {
        foreach (dynamic D in Gd.Iter(Snap.Doors))
        {
            if ((D <= 0))
            {
                return true;
            }
        }
        return false;
    }

    public void DrawActivity(dynamic Foot, dynamic Aim, dynamic Activity)
    {
        if (Activity == "repair")
        {
            dynamic Centre = (Foot - Gd.MakeVector2(0, 15));
            dynamic Angle = (Aim + (Gd.Sin((Clock * 12)) * 0.8f));
            dynamic Tip = (Centre + (Vector2.FromAngle(Angle) * 20));
            dynamic Side = (Vector2.FromAngle(Angle).Orthogonal() * 5);
            Gd.Native(this, "draw_line", Centre, Tip, INK, 5);
            Gd.Native(this, "draw_line", Centre, Tip, Gd.MakeColor("AD7C48"), 3);
            Gd.Native(this, "draw_line", (Tip - Side), (Tip + Side), INK, 7);
            Gd.Native(this, "draw_line", (Tip - Side), (Tip + Side), Gd.MakeColor("B9C6CC"), 4);
        }
        else if (Gd.Contains(new GArray("heal", "revive"), Activity))
        {
            dynamic Centre = (Foot - Gd.MakeVector2(0, 18));
            dynamic Pulse = (0.7f + (0.3f * Gd.Sin((Clock * 8))));
            Gd.Native(this, "draw_line", (Centre - Gd.MakeVector2(4, 0)), (Centre + Gd.MakeVector2(4, 0)), Gd.MakeColor(0.4f, 1.8f, 0.7f, Pulse), 3);
