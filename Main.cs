    public override void _Ready()
    {
        this.BuildScene();
        this.BuildUi();
        dynamic Args = Gd.Static(typeof(OS), "get_cmdline_user_args");
        foreach (dynamic A in Gd.Iter(Args))
        {
            if (Gd.Truth(Gd.BeginsWith(A, "--shot=")))
            {
                ShotPath = Gd.Substr(A, 7);
            }
            else if (Gd.Truth(Gd.BeginsWith(A, "--shot-at=")))
            {
                ShotAt = Gd.ToFloat(Gd.Substr(A, 10));
            }
            else if (Gd.Truth(Gd.BeginsWith(A, "--at=")))
            {
                dynamic Xy = Gd.Split(Gd.Substr(A, 5), ",");
                ShotPos = (Gd.MakeVector2(Gd.ToFloat(Gd.At(Xy, 0)), Gd.ToFloat(Gd.At(Xy, 1))) * T);
            }
        }
        if ((Gd.Contains(Args, "--autoplay") || Gd.Contains(Args, "--autohost") || Gd.Contains(Args, "--autolobby")))
        {
            this.StartLocal();
            dynamic Nb = 2;
            foreach (dynamic A in Gd.Iter(Args))
            {
                if (Gd.Truth(Gd.BeginsWith(A, "--bots=")))
                {
                    Nb = Gd.ToInt(Gd.Substr(A, 7));
                }
            }
            foreach (dynamic I in Gd.Iter(Nb))
            {
                Sim.Action(1, "add_bot", 0);
            }
            if (!Gd.Contains(Args, "--autolobby"))
            {
                Sim.Action(1, "start", 0);
            }
            if (Gd.Contains(Args, "--night"))
            {
                Sim.Action(1, "skip", 0);
                Sim.Tick(0.01f);
                Sim.TimeLeft = 0.0f;
                Sim.Tick(0.01f);
                Sim.Elapsed = Gd.Maxf(0.0f, (GameSim.FIRST_WAVE_DELAY - 0.5f));
            }
            this.DevArgs(Args);
        }
    }

