    // compass octant (0 = right, counting clockwise on screen) to the sheet row
    public static readonly int[] OCT_ROW = { 0, 4, 1, 5, 2, 6, 3, 7 };

    public void Char(dynamic Key, dynamic Skin, dynamic Foot, dynamic Aim, dynamic S, dynamic Mod, dynamic Lock = null, dynamic Activity = null)
    {
        Lock ??= false;
        Activity ??= "idle";
        // A pixel-art character: the walk cycle while it moves, idle breathing otherwise.
        // While it walks it faces where it walks (no moonwalking); standing still it faces `aim` (the mouse),
        // and with `lock` (fighting) it faces `aim` even on the move. With aim null (enemies) it faces its walk.
        dynamic M = Gd.Get(Cmove, Key, new GArray(Foot, (-1.0f), (Mathf.Pi / 2), (-1)));
        Vector2 Step = (Vector2)((Foot - Gd.At(M, 0)));
        if ((Gd.Length(Step) > 0.2f))
        {
            M[1] = Clock;
            M[2] = Step.Angle();
        }
        M[0] = Foot;
        Cmove[Key] = M;
        dynamic Tex = Gd.Get(Csheet, Skin);
        if ((Tex == null))
        {
            return;
        }
        bool Moving = Gd.Truth(((Clock - Gd.At(M, 1)) < 0.15f));
        dynamic Anim = (Gd.Truth(Moving) ? (dynamic)("run") : "idle");
        float Ang = Gd.Float((((Aim == null) || (Gd.Truth(Moving) && !(Gd.Truth(Lock)))) ? (dynamic)(Gd.At(M, 2)) : Aim));
        // 8 directions. Sheet rows: right, down, left, up, then down-right, down-left, up-left, up-right.
        // The facing only changes once the angle is well past the edge between two directions, so walking
        // diagonally (two keys) or sliding along a wall never flickers between neighbouring rows.
        dynamic C0 = Gd.At(Cinfo.Chars, Skin);
        int Rows = Gd.Int((Tex.GetHeight() / C0.Size));
        int Dir;
        if ((Rows >= 8))
        {
            int Oct = Gd.Wrapi(Gd.Roundi((Ang / (Mathf.Pi / 4.0f))), 0, 8);
            int Last = Gd.Int(Gd.At(M, 3));
            if (((Last >= 0) && (Mathf.Abs(Mathf.AngleDifference(Ang, ((Last * Mathf.Pi) / 4.0f))) < ((Mathf.Pi / 8.0f) + 0.2f))))
            {
                Oct = Last;
            }
            M[3] = Oct;
            Dir = OCT_ROW[Oct];
        }
        else
        {
            Dir = Gd.Wrapi(Gd.Roundi((Ang / (Mathf.Pi / 2.0f))), 0, 4);
        }
        string State = ((Activity != "idle") ? (dynamic)(Activity) : Anim);
        dynamic Timing = Gd.Get(AnimState, Key, new GArray(State, Clock));
        if ((Gd.At(Timing, 0) != State))
        {
            Timing = new GArray(State, Clock);
        }
        AnimState[Key] = Timing;
        float PhaseTime = Gd.Float((Clock - Gd.At(Timing, 1)));
        if (Gd.Contains(new GArray("gather", "repair", "attack"), Activity))
        {
            Foot += ((Gd.MakeVector2(Gd.Cos(Ang), 0) * Gd.Sin((PhaseTime * 12.0f))) * 2.0f);
        }
        else if (Gd.Contains(new GArray("heal", "revive"), Activity))
        {
            Foot.Y += 2.0f;
        }
        dynamic Fr = Gd.At(Cinfo.Frames, Anim);
        // out of step with each other
        int K = Gd.Int((Gd.Int((PhaseTime * Gd.At(Cinfo.Fps, Anim))) % Gd.Int(Gd.At(Fr, 1))));
        if ((Gd.Truth(Moving) && (Gd.Cos((Gd.At(M, 2) - Ang)) < (-0.2f))))
        {
            K = ((Gd.Int(Gd.At(Fr, 1)) - 1) - K);
        }
        int F = Gd.Int((Gd.Int(Gd.At(Fr, 0)) + K));
        dynamic C = Gd.At(Cinfo.Chars, Skin);
        dynamic Size = Gd.MakeVector2(C.Size, C.Size);
        dynamic Anchor = Gd.MakeVector2(Gd.At(C.Anchor, 0), Gd.At(C.Anchor, 1));
        Gd.Native(this, "draw_texture_rect_region", Tex, Gd.MakeRect2((Foot - (Anchor * S)), (Size * S)), Gd.MakeRect2((Gd.MakeVector2(F, Dir) * Size), Size), Mod);
    }

    // A node shrinks toward its foot as it is gathered: full at 5 units, under half its size on the last one,
    // also within the unit being gathered right now, and it wobbles while someone works it. Once empty it shows
    // its remains (stump, rubble, ...) at full size.
    public dynamic NodeShown = new GDict {  };
    public float NodeShownClock = 0.0f;

    public float NodeScale(dynamic Nd)
    {
        Vector2 Pos = (Vector2)Gd.At(Nd, 1);
        float Amount = Gd.Float(Gd.At(Nd, 2));
        if ((Amount <= 0))
        {
            Gd.Erase(NodeShown, Pos);
            return 1.0f;
        }
        float Work = 0.0f;
        foreach (dynamic Id in Gd.Iter(Snap.Ps))
        {
            dynamic P = Gd.At(Snap.Ps, Id);
            if (((Gd.At(P, 22) == "gather") && (((Vector2)Gd.At(P, 23)).DistanceTo(Pos) < 1.0f)))
            {
                Work = Gd.Maxf(Work, Gd.Float(Gd.At(P, 21)));
            }
        }
        float Left = Gd.Clampf(((Amount - Work) / 5.0f), 0.0f, 1.0f);
        float Target = (0.45f + (0.55f * Left));
        float Shown = Gd.Float(Gd.Get(NodeShown, Pos, Target));
        // ease toward the target so each unit taken shrinks it smoothly
        float Step = Gd.Clampf((Clock - NodeShownClock), 0.0f, 0.1f);
        Shown = Gd.Lerpf(Shown, Target, (1.0f - Gd.Exp((-10.0f * Step))));
        NodeShown[Pos] = Shown;
        if ((Work > 0))
        {
            Shown *= (1.0f + (0.035f * Gd.Sin((Clock * 28.0f))));
        }
        return Shown;
    }

