    public dynamic RoundRect(dynamic Half, dynamic R)
    {
        // Outline of the base rectangle grown by r (a rectangle with corners rounded by r).
        dynamic Pts = Gd.PackedVector2Array();
        foreach (dynamic C in Gd.Iter(new GArray(new GArray(Gd.MakeVector2(Half.X, Half.Y), 0.0f), new GArray(Gd.MakeVector2((-Half.X), Half.Y), (Mathf.Pi / 2)), new GArray(Gd.MakeVector2((-Half.X), (-Half.Y)), Mathf.Pi), new GArray(Gd.MakeVector2(Half.X, (-Half.Y)), (Mathf.Pi * 1.5f)))))
