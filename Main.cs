    // --boss=0..6 (night 2 with that boss 9 tiles in front of door A, you beside it).
    public void DevArgs(dynamic Args)
    {
        foreach (dynamic A in Gd.Iter(Args))
        {
            dynamic Me = Gd.Get(Sim.Players, 1);
            if (((Me == null) || (Sim.Phase == "lobby")))
            {
                return;
            }
            if (Gd.Equal(A, "--kit"))
            {
                Sim.SetCount(Me, "wood", 30);
                Sim.SetCount(Me, "stone", 12);
                Sim.SetCount(Me, "titanium", 8);
                Sim.SetCount(Me, "bow", 1);
                Sim.SetCount(Me, "arrow", 10);
                Sim.SetCount(Me, "bandage", 2);
                Sim.Unlock = 2;
            }
            else if (Gd.Equal(A, "--arsenal"))
            {
                // every weapon in the hotbar (keys 1-4: spear, blade, hammer, bow) to look at each attack; for fists,
                // drag one of them into the bag (Tab) and select the empty slot
                Me.Inv = GameSim.EmptySlots(GameSim.INV_SLOTS);
                Me.Inv[0] = new GArray("stone_spear", 1);
                Me.Inv[1] = new GArray("titanium_blade", 1);
                Me.Inv[2] = new GArray("hammer", 1);
                Me.Inv[3] = new GArray("bow", 1);
                Sim.SetCount(Me, "arrow", 99);
                Me.Sel = 0;
            }
            else if (Gd.Equal(A, "--walls"))
            {
                // a wood and a stone wall beside door A, to look at
                Vector2 D = (Vector2)((Gd.At(GameSim.DOOR_POS, 0) + ((Gd.At(GameSim.DOOR_DIR, 0) * 5) * T)));
                Gd.Append(Sim.BuiltWalls, new GDict { { "id", 9001 }, { "kind", "wood" }, { "pos", GameSim.SnapToTile((D + Gd.MakeVector2(0, (-3 * T)))) }, { "vert", true }, { "hp", 200.0f }, { "maxhp", 200.0f } });
                Gd.Append(Sim.BuiltWalls, new GDict { { "id", 9002 }, { "kind", "stone" }, { "pos", GameSim.SnapToTile((D + Gd.MakeVector2((-2 * T), (4 * T)))) }, { "vert", false }, { "hp", 300.0f }, { "maxhp", 400.0f } });
                Sim.Teleport(Me, (D + Gd.MakeVector2((2 * T), 0)));
            }
            else if (Gd.Equal(A, "--towers"))
            {
                // a tower beside each landing pad (the third one badly damaged), you beside the first
                Sim.FreeTower = false;
                for (int I = 0; I < GameSim.MAX_TOWERS; I++)
                {
                    Sim.PlaceTower(I, Sim.FreeTowerSpot(I));
                }
                Gd.At(Sim.Towers, 2).Hp = 60.0f;
                Sim.World.Rebuild(Sim.Nodes, Sim.Towers, Sim.BuiltWalls);
                Sim.Teleport(Me, (Gd.At(Sim.Towers, 0).Pos + Gd.MakeVector2((-2 * T), (-1.0f * T))));
            }
            else if (Gd.Truth(Gd.BeginsWith(A, "--gathered=")))
            {
                // every node left with N units (0..5), to look at the broken stages
                foreach (dynamic Nd in Gd.Iter(Sim.Nodes))
                {
                    Nd.Amount = Gd.ToInt(Gd.Substr(A, 11));
                }
            }
            else if (Gd.Contains(GameSim.RES, Gd.Substr(A, 7)) && Gd.Truth(Gd.BeginsWith(A, "--goto=")))
            {
                // --goto=wood|stone|herb|titanium: next to the nearest node of that kind (titanium is all in the outer zone)
                int Kind = Gd.Int(Gd.Find(GameSim.RES, Gd.Substr(A, 7)));
                Vector2 Best = Vector2.Zero;
                foreach (dynamic Nd in Gd.Iter(Sim.Nodes))
                {
                    if ((Gd.Int(Nd.Type) == Kind) && ((Best == Vector2.Zero) || (((Vector2)Nd.Pos).Length() < Best.Length())))
                    {
