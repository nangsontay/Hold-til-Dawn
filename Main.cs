    // --- per-frame ----------------------------------------------------------
    public override void _Process(double delta)
    {
        dynamic Dt = (float)delta;
        if ((Gd.Truth(Sim) && (MyId == 0)))
        {
            // dedicated server draws nothing
            return;
        }
        Clock += Dt;
        TickLandmarkGround();
        LocalNoteT -= Dt;
        // Your own character moves every rendered frame (not at the 60 Hz physics rate), so it glides at any
        // monitor refresh rate; the simulation still checks every position it receives.
        if (((MyId != 0) && Gd.Truth(Gd.Has(Snap, "ps")) && !Gd.Truth(Paused)))
        {
            this.Move(Gd.Minf(Dt, 0.05f));
        }
        string Ph = Gd.Get(Snap, "ph", "");
        dynamic InGame = Gd.Contains(new GArray("day", "dusk", "night", "result"), Ph);
        MenuPanel.Visible = (Ph == "");
        LobbyPanel.Visible = (Ph == "lobby");
        Banner.Visible = (Gd.Truth(InGame) && (Ph != "result"));
        Front.Visible = !(Gd.Truth(InGame));
        if (Gd.Truth(Front.Visible))
        {
            Front.QueueRedraw();
            this.LayoutFrontend();
        }
        dynamic MeNow = Gd.Get(Gd.Get(Snap, "ps", new GDict {  }), MyId);
        if (((Ph != "day") && (Ph != "dusk") && !(((Ph == "night") && (MeNow != null) && Gd.Truth(Gd.At(MeNow, 19))))))
        {
            CraftOpen = false;
        }
        this.KeepPanelsInReach(MeNow);
        if (!Gd.Contains(new GArray("day", "dusk", "night"), Ph))
        {
            BagOpen = false;
            Paused = false;
            this.CloseBuild();
        }
        // the large map covers the middle of the screen: the radio line waits until it closes
        // the large map and the workbench tab hide the radio line
        Banner.Text = ((Gd.Truth(MapBig) || Gd.Truth(CraftOpen)) ? "" : Gd.Get(Snap, "msg", ""));
        // the night bar pushes the boss bar down (src/ai/view/Main.EnemyView.cs); the banner moves down with it
        bool BossShown = ((Ph == "night") && Gd.Truth(Gd.Any(Gd.Get(Snap, "en", new GArray()), (Func<dynamic, dynamic>)((E) => (Gd.At(E, 1) == GameSim.BOSS)))));
        Banner.OffsetTop = (BossShown ? (86 + NIGHT_BAR_H) : ((Ph == "night") ? (60 + NIGHT_BAR_H) : 86));
        if ((Ph == "lobby"))
        {
            this.LobbyUi();
        }
        Hud.QueueRedraw();
        Gd.Native(this, "queue_redraw");
        if (((ShotPath != "") && (Clock >= ShotAt)))
        {
            this.CaptureShot(ShotPath);
            ShotPath = "";
        }
        if (!(Gd.Truth(InGame)))
        {
            this.ForgetFallen();
            return;
        }
        dynamic A = Gd.Minf(1.0f, (Dt * 15.0f));
        dynamic Ne = new GDict {  };
        foreach (dynamic E in Gd.Iter(Snap.En))
        {
            Ne[Gd.At(E, 0)] = Gd.Get(ShownE, Gd.At(E, 0), Gd.At(E, 2)).Lerp(Gd.At(E, 2), A);
        }
        // enemies gone since the last frame fall over where they were (src/ai/view/Main.EnemyView.cs)
        this.NoteFallen(Ne);
        ShownE = Ne;
        foreach (dynamic Id in Gd.Iter(Snap.Ps))
        {
            ShownP[Id] = Gd.Get(ShownP, Id, Gd.At(Gd.At(Snap.Ps, Id), 2)).Lerp(Gd.At(Gd.At(Snap.Ps, Id), 2), A);
        }
        foreach (dynamic Id in Gd.Iter(Gd.Keys(Flash)))
        {
            Flash[Id] -= Dt;
            if ((Gd.At(Flash, Id) <= 0))
            {
                Gd.Erase(Flash, Id);
            }
        }
        dynamic Damp = Gd.Pow(0.02f, Dt);
        foreach (dynamic F in Gd.Iter(Fx))
        {
            F.Pos += (F.Vel * Dt);
            F.Vel *= Damp;
            F.Life -= Dt;
        }
        Fx = Gd.Filter(Fx, (Func<dynamic, dynamic>)((F) => (F.Life > 0)));
        foreach (dynamic P in Gd.Iter(Popups))
        {
            P.Life -= Dt;
        }
        Popups = Gd.Filter(Popups, (Func<dynamic, dynamic>)((P) => (P.Life > 0)));
        Hurt = Gd.Maxf(0.0f, (Hurt - Dt));
        GenFlash = Gd.Maxf(0.0f, (GenFlash - Dt));
        foreach (dynamic I in Gd.Iter(3))
        {
            DoorFlash[I] = Gd.Maxf(0.0f, (Gd.At(DoorFlash, I) - Dt));
        }
        Shake = Gd.MoveToward(Shake, 0.0f, (Dt * 30.0f));
        Cam.Offset = (Gd.MakeVector2((float)GD.RandRange((-1), 1), (float)GD.RandRange((-1), 1)) * Shake);
        dynamic Target = (LocalPos - Gd.MakeVector2(0, LIFT));
        if ((CameraTp != LocalTp))
        {
            CameraTp = LocalTp;
            CameraFocus = Target;
            Cam.Position = Target;
        }
        Vector2 Zone = DisplaySettings.Current.CameraDeadZone;
        dynamic Delta = (Target - CameraFocus);
        CameraFocus += Gd.MakeVector2((Gd.Signf(Delta.X) * Gd.Maxf(0, (Gd.Absf(Delta.X) - Zone.X))), (Gd.Signf(Delta.Y) * Gd.Maxf(0, (Gd.Absf(Delta.Y) - Zone.Y))));
        Vector2 Follow = Cam.Position.Lerp(CameraFocus, (1.0f - Gd.Exp(((-DisplaySettings.Current.CameraFollowRate) * Dt))));
        // zoom so one art pixel covers a whole number of screen pixels: crisp pixel art at any window size
        dynamic Ws = Gd.MakeVector2(Gd.Static(typeof(DisplayServer), "window_get_size"));
        // the canvas_items stretch scale
        dynamic Sc = Gd.Minf((Ws.X / 960.0f), (Ws.Y / 540.0f));
        Cam.Zoom = (Vector2.One * Gd.Maxf(1.0f, (Gd.At(ZOOMS, ZoomI) / Sc)));
        // snap the camera to whole screen pixels, not whole art pixels: the world scrolls one screen pixel at a
        // time instead of jumping 3 at a time, and every art pixel still covers exactly the same screen pixels
        float ScreenPx = Gd.Float((Cam.Zoom.X * Sc));
        Cam.Position = ((Follow * ScreenPx).Round() / ScreenPx);
        if (((ShotPos != null) && (Clock > 0.5f)))
        {
            LocalPos = ShotPos;
            ShotPos = null;
        }
        dynamic Me = Gd.Get(Snap.Ps, MyId);
        dynamic Night = 0.0f;
        if ((Ph == "night"))
        {
            Night = 1.0f;
        }
        else if ((Ph == "dusk"))
        {
            Night = (1.0f - (Snap.TimeLeft / GameSim.DUSK));
        }
        NightLevel = (float)Night;
        Tint.Color = DAY_TINT.Lerp(NIGHT_TINT, Night);
        this.TickBaseLamps((float)Night);
        MyLight.Enabled = (Night > 0);
        Beacon.Enabled = (Night > 0);
        foreach (dynamic L in Gd.Iter(TowerLights))
        {
            L.Enabled = false;
        }
        foreach (dynamic Tw in Gd.Iter(Gd.Get(Snap, "tw", new GArray())))
        {
            dynamic L = Gd.At(TowerLights, Gd.At(Tw, 0));
            // a standing tower floodlights the ground around it (TOWER_LIGHT, 6 tiles) from dusk to dawn; the light
            // goes out the moment the tower falls and flickers while it is badly damaged
            L.Enabled = ((Night > 0.02f) && (Gd.At(Tw, 2) > 0));
            L.Position = Gd.At(Tw, 1);
            L.Energy = ((0.85f * Night) * ((Gd.At(Tw, 2) < (0.3f * GameSim.TOWER_HP)) ? (dynamic)((float)GD.RandRange(0.45f, 1.0f)) : 1.0f));
        }
        this.TickSupplyLights((float)Night);
        MyLight.Position = LocalPos;
        if ((Me != null))
        {
            dynamic R = ((4.0f * T) * ((Gd.At(Me, 1) == 0) ? (dynamic)(1.3f) : 1.0f));
            MyLight.TextureScale = ((Gd.Lerpf((30.0f * T), R, Night) * 2.0f) / 256.0f);
        }
    }

