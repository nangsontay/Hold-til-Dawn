    public override void _PhysicsProcess(double delta)
    {
        dynamic Dt = (float)delta;
        if (Gd.Truth(Sim))
        {
            Sim.Tick(Dt);
            Frame += 1;
            // the renderer reads a snapshot 20 times per second, as a client would
            if (((Frame % 3) == 0))
            {
                this.OnSnap(Gd.FromVariant(Sim.Snapshot()));
            }
        }
        if (((MyId != 0) && Gd.Truth(Gd.Has(Snap, "ps"))))
        {
            this.Move(Dt);
        }
    }

    public void Move(dynamic Dt)
    {
        dynamic Me = Gd.Get(Snap.Ps, MyId);
        if ((Me == null))
        {
            return;
        }
        if ((Gd.At(Me, 15) != LocalTp))
        {
            LocalTp = Gd.At(Me, 15);
            LocalPos = Gd.At(Me, 2);
            Gd.Clear(PendingInputs);
        }
        bool Playing = Gd.Truth(Gd.Contains(new GArray("day", "dusk", "night"), Snap.Ph));
        if ((Gd.Truth(Playing) && (Gd.At(Me, 5) == 0)))
        {
            dynamic Dir = Gd.MakeVector2((this.Key(68) - this.Key(65)), (this.Key(83) - this.Key(87)));
            dynamic Destination = (LocalPos + (((Dir.Normalized() * GameSim.SPEED) * ((Gd.At(Me, 1) == 0) ? (dynamic)(1.2f) : 1.0f)) * Dt));
            LocalPos = Geometry.MoveBody(LocalPos, Destination, BODY_R, GameSim.Walls(this.DoorsOpen()));
            LocalPos = this.Bump(LocalPos, BODY_R);
        }
        LocalPos = LocalPos.LimitLength(GameSim.ISLAND);
        LocalPos = GameSim.Collide(LocalPos, (0.4f * T), this.DoorsOpen());
        if (((Snap.Ph == "night") && !(Gd.Truth(this.Breach())) && !(Gd.Truth(Gd.At(Me, 19)))))
        {
            LocalPos = GameSim.PushOut(LocalPos, (0.4f * T));
        }
        SendAcc += Dt;
        if ((SendAcc >= 0.05f))
        {
            SendAcc = 0.0f;
            // from the body, not the feet
            dynamic Aim = (Gd.Native(this, "get_global_mouse_position") - (LocalPos - Gd.MakeVector2(0, LIFT))).Angle();
            dynamic Atk = (Gd.Truth(Playing) && Gd.Truth(Gd.Static(typeof(Input), "is_mouse_button_pressed", 1)));
            dynamic Inter = (Gd.Truth(Playing) && Gd.Truth(Gd.Static(typeof(Input), "is_physical_key_pressed", 69)));
            dynamic Ent = (Gd.Truth(Playing) && Gd.Truth(Gd.Static(typeof(Input), "is_physical_key_pressed", 70)));
            InputSequence += 1;
            PendingInputs[InputSequence] = LocalPos;
            if ((Gd.Size(PendingInputs) > 128))
            {
                Gd.Erase(PendingInputs, Gd.At(Gd.Keys(PendingInputs), 0));
            }
            if (Gd.Truth(Sim))
            {
                Sim.Input(MyId, LocalPos, Aim, Atk, Inter, Ent, LocalTp, InputSequence);
            }
        }
    }

    public override void _UnhandledInput(InputEvent inputEvent)
    {
        dynamic Ev = Gd.Wrap(inputEvent);
        if ((Gd.IsType(Ev, typeof(InputEventKey)) && Gd.Truth(Ev.Pressed) && !(Gd.Truth(Ev.Echo)) && (Ev.Keycode == 4194334)))
        {
            DebugGeometry = !(Gd.Truth(DebugGeometry));
        }
        if (((MyId == 0) || !(Gd.Truth(Gd.Has(Snap, "ph")))))
        {
            return;
        }
        if ((Gd.IsType(Ev, typeof(InputEventKey)) && Gd.Truth(Ev.Pressed) && !(Gd.Truth(Ev.Echo))))
        {
            if (Gd.Equal(Ev.PhysicalKeycode, 4194305))
            {
                this.BackToMenu("Left the match");
            }
            else
            {
                this.GameplayKey(Ev.PhysicalKeycode);
            }
        }
        else if ((Gd.IsType(Ev, typeof(InputEventMouseButton)) && Gd.Truth(Ev.Pressed) && (Ev.ButtonIndex == 2)))
        {
            this.GameplayRightClick();
        }
        else if ((Gd.IsType(Ev, typeof(InputEventMouseButton)) && Gd.Truth(Ev.Pressed) && Gd.Contains(new GArray(4, 5), Ev.ButtonIndex)))
        {
            ZoomI = Gd.Clampi((ZoomI + ((Ev.ButtonIndex == 4) ? (dynamic)(1) : (-1))), 0, (Gd.Size(ZOOMS) - 1));
        }
    }

    // --- hit feedback (derived from snapshot diffs, no extra network) -------
    public void OnSnap(dynamic D)
    {
        bool Same = Gd.Truth(((Gd.Get(D, "ph") == Gd.Get(Snap, "ph")) && (Gd.Get(D, "k") == Gd.Get(Snap, "k"))));
        if ((Gd.Truth(Same) && Gd.Contains(new GArray("day", "dusk", "night"), D.Ph)))
        {
            dynamic Seen = new GDict {  };
            foreach (dynamic E in Gd.Iter(D.En))
            {
                Seen[Gd.At(E, 0)] = true;
                dynamic Old = Gd.Get(PrevHp, Gd.At(E, 0));
                if (((Old != null) && (Gd.At(E, 3) < Old)))
                {
                    // 2.5D: hits land on the body, not the feet
                    Vector2 Body = (Vector2)((Gd.At(E, 2) - Gd.MakeVector2(0, Gd.At(E, 5))));
                    this.Popup(Body, Gd.Str(Gd.Roundi((Old - Gd.At(E, 3)))), NEON_CYAN, ((Gd.At(E, 1) == GameSim.BOSS) ? (dynamic)(18) : 15));
                    Flash[Gd.At(E, 0)] = 0.1f;
                    this.Sparks(Body, 4, Gd.MakeColor(1.6f, 1.6f, 2.0f));
                }
            }
            foreach (dynamic Id in Gd.Iter(PrevPos))
            {
                if (!(Gd.Truth(Gd.Has(Seen, Id))))
                {
                    this.Sparks(Gd.At(PrevPos, Id), 16, NEON_PINK, 260.0f);
                }
            }
            if ((D.Base < Snap.Base))
            {
                GenFlash = 0.4f;
                Shake = Gd.Maxf(Shake, 2.0f);
            }
            foreach (dynamic I in Gd.Iter(3))
            {
                if ((Gd.At(D.Doors, I) < Gd.At(Snap.Doors, I)))
                {
                    DoorFlash[I] = 0.4f;
                }
                else if ((Gd.At(D.Doors, I) > Gd.At(Snap.Doors, I)))
                {
                    this.Sparks(Gd.At(GameSim.DOOR_POS, I), 3, Gd.MakeColor(2.2f, 1.7f, 0.6f), 90.0f);
                }
            }
        }
        if (Gd.Truth(Same))
        {
            foreach (dynamic Id in Gd.Iter(D.Ps))
            {
                dynamic P = Gd.At(D.Ps, Id);
                dynamic Old = Gd.Get(PrevPhp, Id);
                if (((Old != null) && (Gd.At(P, 3) < Old)))
                {
                    this.Popup((Gd.At(P, 2) - Gd.MakeVector2(0, LIFT)), Gd.Format("-%d", Gd.Roundi((Old - Gd.At(P, 3)))), NEON_RED, 15);
                    if ((Id == MyId))
                    {
                        Shake = Gd.Maxf(Shake, 7.0f);
                        Hurt = 0.35f;
                    }
                }
            }
        }
        dynamic Mine = Gd.Get(Gd.Get(D, "ps", new GDict {  }), MyId);
        dynamic OldMe = Gd.Get(Gd.Get(Snap, "ps", new GDict {  }), MyId);
        if (((Mine != null) && (OldMe != null)))
        {
            foreach (dynamic Res in Gd.Iter(Gd.At(Mine, 7)))
            {
                int Gain = Gd.Int((Gd.At(Gd.At(Mine, 7), Res) - Gd.Get(Gd.At(OldMe, 7), Res, 0)));
                if ((Gain > 0))
                {
                    this.Popup((Gd.At(Mine, 2) - Gd.MakeVector2(0, LIFT)), Gd.Format("+%d %s", new GArray(Gain, Res)), (Gd.Get(DROP_COL, Res, Colors.White) * 1.6f), 14);
                }
            }
        }
        Gd.Clear(PrevHp);
        Gd.Clear(PrevPos);
        foreach (dynamic E in Gd.Iter(Gd.Get(D, "en", new GArray())))
        {
            PrevHp[Gd.At(E, 0)] = Gd.At(E, 3);
            PrevPos[Gd.At(E, 0)] = (Gd.At(E, 2) - Gd.MakeVector2(0, Gd.At(E, 5)));
        }
        Gd.Clear(PrevPhp);
        foreach (dynamic Id in Gd.Iter(Gd.Get(D, "ps", new GDict {  })))
        {
            PrevPhp[Id] = Gd.At(Gd.At(D.Ps, Id), 3);
        }
        Geometry.Rebuild(Gd.Map(Gd.Get(D, "nodes", new GArray()), (Func<dynamic, dynamic>)((N) => new GDict { { "type", Gd.At(N, 0) }, { "pos", Gd.At(N, 1) }, { "amount", Gd.At(N, 2) } })), Gd.Map(Gd.Get(D, "tw", new GArray()), (Func<dynamic, dynamic>)((Tw) => new GDict { { "pos", Gd.At(Tw, 1) } })));
        if (((Mine != null) && (Gd.At(Mine, 15) == LocalTp) && (Gd.Size(Mine) > 24)))
        {
            int Acknowledged = Gd.Int(Gd.At(Mine, 24));
            if (Gd.Truth(Gd.Has(PendingInputs, Acknowledged)))
            {
                Vector2 Correction = (Vector2)((Gd.At(Mine, 2) - Gd.At(PendingInputs, Acknowledged)));
                LocalPos += Correction;
                foreach (dynamic Sequence in Gd.Iter(Gd.Keys(PendingInputs)))
                {
                    if ((Sequence <= Acknowledged))
                    {
                        Gd.Erase(PendingInputs, Sequence);
                    }
                    else
                    {
                        PendingInputs[Sequence] += Correction;
                    }
                }
            }
        }
        Snap = D;
    }

