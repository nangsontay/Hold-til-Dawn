    // --- per-frame ----------------------------------------------------------
    public override void _Process(double delta)
    {
        dynamic Dt = (float)delta;
        if ((Gd.Truth(Sim) && (MyId == 0)))
        {
            // dedicated server draws nothing
            return;
        }
        Clock += Dt;
        string Ph = Gd.Get(Snap, "ph", "");
        dynamic InGame = Gd.Contains(new GArray("day", "dusk", "night", "result"), Ph);
        MenuPanel.Visible = (Ph == "");
        LobbyPanel.Visible = (Ph == "lobby");
        Banner.Visible = InGame;
        Front.Visible = !(Gd.Truth(InGame));
        if (Gd.Truth(Front.Visible))
        {
            Front.QueueRedraw();
            this.LayoutFrontend();
        }
        dynamic MeNow = Gd.Get(Gd.Get(Snap, "ps", new GDict {  }), MyId);
        if (((Ph != "day") && (Ph != "dusk") && !(((Ph == "night") && (MeNow != null) && Gd.Truth(Gd.At(MeNow, 19))))))
        {
            CraftOpen = false;
        }
        Banner.Text = Gd.Get(Snap, "msg", "");
        if ((Ph == "lobby"))
        {
            this.LobbyUi();
        }
        Hud.QueueRedraw();
        Gd.Native(this, "queue_redraw");
        if (((ShotPath != "") && (Clock >= ShotAt)))
        {
            this.CaptureShot(ShotPath);
            ShotPath = "";
        }
        if (!(Gd.Truth(InGame)))
        {
            return;
        }
        dynamic A = Gd.Minf(1.0f, (Dt * 15.0f));
        dynamic Ne = new GDict {  };
        foreach (dynamic E in Gd.Iter(Snap.En))
        {
            Ne[Gd.At(E, 0)] = Gd.Get(ShownE, Gd.At(E, 0), Gd.At(E, 2)).Lerp(Gd.At(E, 2), A);
        }
        ShownE = Ne;
        foreach (dynamic Id in Gd.Iter(Snap.Ps))
        {
            ShownP[Id] = Gd.Get(ShownP, Id, Gd.At(Gd.At(Snap.Ps, Id), 2)).Lerp(Gd.At(Gd.At(Snap.Ps, Id), 2), A);
        }
        foreach (dynamic Id in Gd.Iter(Gd.Keys(Flash)))
        {
            Flash[Id] -= Dt;
            if ((Gd.At(Flash, Id) <= 0))
            {
                Gd.Erase(Flash, Id);
            }
        }
        dynamic Damp = Gd.Pow(0.02f, Dt);
        foreach (dynamic F in Gd.Iter(Fx))
        {
            F.Pos += (F.Vel * Dt);
            F.Vel *= Damp;
            F.Life -= Dt;
        }
        Fx = Gd.Filter(Fx, (Func<dynamic, dynamic>)((F) => (F.Life > 0)));
        foreach (dynamic P in Gd.Iter(Popups))
        {
            P.Life -= Dt;
        }
        Popups = Gd.Filter(Popups, (Func<dynamic, dynamic>)((P) => (P.Life > 0)));
        Hurt = Gd.Maxf(0.0f, (Hurt - Dt));
        GenFlash = Gd.Maxf(0.0f, (GenFlash - Dt));
        foreach (dynamic I in Gd.Iter(3))
        {
            DoorFlash[I] = Gd.Maxf(0.0f, (Gd.At(DoorFlash, I) - Dt));
        }
        Shake = Gd.MoveToward(Shake, 0.0f, (Dt * 30.0f));
        Cam.Offset = (Gd.MakeVector2((float)GD.RandRange((-1), 1), (float)GD.RandRange((-1), 1)) * Shake);
        dynamic Target = (LocalPos - Gd.MakeVector2(0, LIFT));
        if ((CameraTp != LocalTp))
        {
            CameraTp = LocalTp;
            CameraFocus = Target;
            Cam.Position = Target;
        }
        Vector2 Zone = DisplaySettings.Current.CameraDeadZone;
        dynamic Delta = (Target - CameraFocus);
        CameraFocus += Gd.MakeVector2((Gd.Signf(Delta.X) * Gd.Maxf(0, (Gd.Absf(Delta.X) - Zone.X))), (Gd.Signf(Delta.Y) * Gd.Maxf(0, (Gd.Absf(Delta.Y) - Zone.Y))));
