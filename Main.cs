    public void Text(dynamic Ci, dynamic Pos, dynamic S, dynamic Size, dynamic Col, dynamic Align = null, dynamic Width = null, dynamic Title = null)
    {
        Align ??= 0;
        Width ??= (-1.0f);
        Title ??= false;
        // HUD text with a dark outline; title = Jersey 10 (headings, timer, big numbers), otherwise Pixelify Sans.
        dynamic Font = (Gd.Truth(Title) ? (dynamic)(FontTitle) : FontUi);
        dynamic Fs = (Gd.Truth(Title) ? (dynamic)(Gd.Roundi((Size * TITLE_SCALE))) : Size);
        // thin outline on small text, so pixel letters stay open
        dynamic Ol = ((Fs <= 12) ? (dynamic)(2) : ((Fs < 20) ? (dynamic)(3) : 4));
        Ci.DrawStringOutline(Font, Pos, S, Align, Width, Fs, Ol, Gd.MakeColor(0, 0, 0, (0.9f * Col.A)));
        Ci.DrawString(Font, Pos, S, Align, Width, Fs, Col);
    }

    public void Panel(dynamic Ci, dynamic R)
    {
        Ci.DrawRect(R, PANEL);
        Ci.DrawRect(R, (GOLD * Gd.MakeColor(1, 1, 1, 0.7f)), false, 1.5f);
    }

    public void Hex(dynamic Ci, dynamic Center, dynamic R, dynamic Col)
    {
        dynamic Pts = Gd.PackedVector2Array();
        foreach (dynamic I in Gd.Iter(6))
        {
            Gd.Append(Pts, (Center + (Vector2.FromAngle(Gd.DegToRad(((60 * I) - 90))) * R)));
        }
        Ci.DrawColoredPolygon(Pts, Col);
    }

    public void Diamond(dynamic Ci, dynamic Center, dynamic R, dynamic Col)
    {
        Ci.DrawColoredPolygon(Gd.PackedVector2Array(new GArray((Center + Gd.MakeVector2(0, (-R))), (Center + Gd.MakeVector2(R, 0)), (Center + Gd.MakeVector2(0, R)), (Center + Gd.MakeVector2((-R), 0)))), Col);
    }

