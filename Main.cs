    public void BuildScene()
    {
        // sea
        Gd.Static(typeof(RenderingServer), "set_default_clear_color", Gd.MakeColor("0E1726"));
        dynamic Env = Gd.Wrap(new Environment());
        Env.BackgroundMode = Gd.EnumValue(typeof(Environment), "BG_CANVAS", 3);
        Env.GlowEnabled = true;
        Env.GlowIntensity = 0.8f;
        Env.GlowHdrThreshold = 1.0f;
        Env.GlowBlendMode = Gd.EnumValue(typeof(Environment), "GLOW_BLEND_MODE_ADDITIVE", 0);
        dynamic We = Gd.Wrap(new WorldEnvironment());
        We.Environment = Env;
        Gd.Native(this, "add_child", We);
        Gd.Native(this, "add_child", Tint);
        Gd.Native(this, "add_child", Cam);
        dynamic G = Gd.Wrap(new Gradient());
        G.SetColor(0, Colors.White);
        G.SetColor(1, Colors.Black);
        G.AddPoint(0.7f, Colors.White);
        dynamic Tex = Gd.Wrap(new GradientTexture2D());
        Tex.Gradient = G;
        Tex.Fill = Gd.EnumValue(typeof(GradientTexture2D), "FILL_RADIAL", 1);
        Tex.FillFrom = Gd.MakeVector2(0.5f, 0.5f);
        Tex.FillTo = Gd.MakeVector2(1.0f, 0.5f);
        Tex.Width = 256;
        Tex.Height = 256;
        MyLight.Texture = Tex;
        Beacon.Texture = Tex;
        Beacon.Color = Gd.MakeColor("F2B544");
        Beacon.TextureScale = ((GameSim.HALF.X * 4.0f) / 256.0f);
        Gd.Native(this, "add_child", MyLight);
        Gd.Native(this, "add_child", Beacon);
        foreach (dynamic I in Gd.Iter(3))
        {
            dynamic Tl = Gd.Wrap(new PointLight2D());
            Tl.Texture = Tex;
            Tl.Color = Gd.MakeColor("F2B544");
            Tl.TextureScale = ((GameSim.TOWER_LIGHT * 2.0f) / 256.0f);
            Tl.Enabled = false;
            Tl.TextureFilter = Gd.EnumValue(typeof(CanvasItem), "TEXTURE_FILTER_LINEAR", 2);
            // the scene repeats its ground texture; a light must not tile
            Tl.TextureRepeat = Gd.EnumValue(typeof(CanvasItem), "TEXTURE_REPEAT_DISABLED", 1);
            Gd.Native(this, "add_child", Tl);
            Gd.Append(TowerLights, Tl);
        }
        dynamic Idx = Gd.FromVariant(Json.ParseString(Gd.Static(typeof(FileAccess), "get_file_as_string", (NATURE + "index.json"))));
        foreach (dynamic N in Gd.Iter(Idx))
        {
            Spr[N] = new GArray(Gd.Load(((NATURE + N) + ".png")), Gd.MakeVector2(Gd.At(Gd.At(Idx, N), 0), Gd.At(Gd.At(Idx, N), 1)));
            // "Pine_2_1" = model Pine_2, turned variant 1
            dynamic Base = Gd.Rsplit(N, "_", true, 1);
            Nvar[Gd.At(Base, 0)] = Gd.Maxi(Gd.Get(Nvar, Gd.At(Base, 0), 0), (Gd.ToInt(Gd.At(Base, 1)) + 1));
        }
        Cinfo = Gd.FromVariant(Json.ParseString(Gd.Static(typeof(FileAccess), "get_file_as_string", (CHARS + "chars.json"))));
        foreach (dynamic N in Gd.Iter(Cinfo.Chars))
        {
            Csheet[N] = Gd.Load(((CHARS + N) + ".png"));
        }
        dynamic Pj = Gd.FromVariant(Json.ParseString(Gd.Static(typeof(FileAccess), "get_file_as_string", (PROPS + "props.json"))));
        foreach (dynamic N in Gd.Iter(Pj))
        {
            Prop[N] = new GArray(Gd.Load(((PROPS + N) + ".png")), Gd.MakeVector2(Gd.At(Gd.At(Pj, N), 0), Gd.At(Gd.At(Pj, N), 1)));
        }
        // light/dark patches so the grass is not one flat colour
        dynamic Fn = Gd.Wrap(new FastNoiseLite());
        Fn.Frequency = 0.018f;
        Fn.FractalOctaves = 3;
        // four flat tones with hard steps: pixel-art ground, like the sprites
        dynamic Ramp = Gd.Wrap(new Gradient());
        Ramp.InterpolationMode = Gd.EnumValue(typeof(Gradient), "GRADIENT_INTERPOLATE_CONSTANT", 1);
        Ramp.Offsets = Gd.PackedFloat32Array(new GArray(0.0f, 0.35f, 0.55f, 0.75f));
        Ramp.Colors = Gd.PackedColorArray(new GArray(Gd.MakeColor(0.87f, 0.89f, 0.85f), Gd.MakeColor(0.92f, 0.94f, 0.9f), Gd.MakeColor(0.96f, 0.97f, 0.94f), Gd.MakeColor(1.0f, 1.0f, 0.97f)));
        GroundTex.Width = 512;
        GroundTex.Height = 512;
        GroundTex.Seamless = true;
        GroundTex.Noise = Fn;
        GroundTex.ColorRamp = Ramp;
        Gd.SetNative(this, "texture_repeat", Gd.EnumValue(typeof(CanvasItem), "TEXTURE_REPEAT_ENABLED", 2));
        // the whole world is pixel art: no smoothing when scaled up
        Gd.SetNative(this, "texture_filter", Gd.EnumValue(typeof(CanvasItem), "TEXTURE_FILTER_NEAREST", 1));
        // light falloff stays soft
        MyLight.TextureFilter = Gd.EnumValue(typeof(CanvasItem), "TEXTURE_FILTER_LINEAR", 2);
        Beacon.TextureFilter = Gd.EnumValue(typeof(CanvasItem), "TEXTURE_FILTER_LINEAR", 2);
        MyLight.TextureRepeat = Gd.EnumValue(typeof(CanvasItem), "TEXTURE_REPEAT_DISABLED", 1);
        Beacon.TextureRepeat = Gd.EnumValue(typeof(CanvasItem), "TEXTURE_REPEAT_DISABLED", 1);
        Deco = Geometry.Deco;
        Scatter = Geometry.Scatter;
    }

