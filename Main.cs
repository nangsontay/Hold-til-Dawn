    public void WallItems(dynamic Items, dynamic R, dynamic Height, dynamic Top, dynamic Face)
    {
        // A horizontal wall is one item. A vertical wall is cut into 1-tile pieces so a player
        // beside it sorts correctly against each piece; the pieces join into one wall.
        if ((R.Size.Y <= R.Size.X))
        {
            Gd.Append(Items, new GArray(R.End.Y, 1, R, Height, Top, Face, true));
            return;
        }
        // corners belong to the long walls
        dynamic Lo = Gd.Maxf(R.Position.Y, ((-GameSim.HALF.Y) + GameSim.WALL_IN));
        dynamic Hi = Gd.Minf(R.End.Y, (GameSim.HALF.Y - GameSim.WALL_IN));
        dynamic Y = Lo;
        while ((Y < (Hi - 0.5f)))
        {
            dynamic Piece = Gd.MakeRect2(R.Position.X, Y, R.Size.X, Gd.Minf(T, (Hi - Y)));
            Gd.Append(Items, new GArray(Piece.End.Y, 1, Piece, Height, Top, Face, ((Y == Lo) && (Lo > (((-GameSim.HALF.Y) + GameSim.WALL_IN) + 0.5f)))));
            Y += T;
        }
    }

