using Godot;
using Environment = Godot.Environment;
using FileAccess = Godot.FileAccess;
using System;
using System.Threading.Tasks;
using HoldTilDawn;

// Owner: Pham Minh Hieu. Inventory, crafting time, bow, walls and result screen checks, run by tests/SimCheck.tscn.
public partial class SimCheck : Node
{
    private void CheckItems()
    {
        // Starting kits and the 8-slot inventory (BAL-18, BAL-42, MEC-09)
        dynamic S = new GameSim();
        S.AddPlayer(1, "Eng", 2);
        S.AddPlayer(2, "Scout", 0);
        S.AddPlayer(3, "Healer", 1);
        S.Action(1, "start", 0);
        dynamic Eng = Gd.At(S.Players, 1);
        dynamic Sc = Gd.At(S.Players, 2);
        dynamic He = Gd.At(S.Players, 3);
        this.Check(((Gd.Size(Eng.Inv) == 8) && (Gd.At(Gd.At(Eng.Inv, 0), 0) == "hammer") && (Gd.Size(Gd.Filter(Eng.Inv, (Func<dynamic, dynamic>)((X) => (X != null)))) == 1)), "Engineer starts with only the hammer in 8 slots");
        this.Check(((Gd.At(Gd.At(Sc.Inv, 0), 0) == "starter_bow") && Gd.Truth(Gd.All(He.Inv, (Func<dynamic, dynamic>)((X) => (X == null)))) && (He.Flasks == 3)), "Scout starts with a starter bow; the Healer with empty hands and 3 flasks");
        this.Check(((He.Weapon == "fists") && (Gd.At(GameSim.WEAPON_STATS["fists"], 0) == 15.0f)), "an empty hand fights bare-handed with the basic weapon's numbers (BAL-08)");
        S.SetCount(Eng, "wood", 45);
        this.Check(((S.Count(Eng, "wood") == 45) && (Gd.At(Gd.At(Eng.Inv, 2), 1) == 20) && (S.Room(Eng, "wood") == 15 + (4 * 20))), "stacks hold 20 units");
        S.SetCount(Eng, "stone", 200);
        this.Check(((S.Count(Eng, "stone") == 80) && (S.Room(Eng, "herb") == 0)), "a full inventory takes no more");
        dynamic Herb = Gd.At(Gd.Filter(S.Nodes, (Func<dynamic, dynamic>)((N) => (N.Type == 2))), 0);
        Eng.Pos = Herb.Pos;
        Eng.Inter = true;
        this.Run(S, 4.0f);
        Eng.Inter = false;
        this.Check(((S.Count(Eng, "herb") == 0) && (Herb.Amount == 5)), "gathering stops when the inventory is full");
        // move to storage and back (needs the storage chest)
        S.SetCount(Eng, "stone", 0);
        S.SetCount(Eng, "wood", 20);
        Eng.Pos = (GameSim.STORAGE_POS + Gd.MakeVector2(0, 24));
        int WoodSlot = Gd.Int(Gd.Find(Gd.Map(Eng.Inv, (Func<dynamic, dynamic>)((X) => ((X != null) ? (dynamic)(Gd.At(X, 0)) : ""))), "wood"));
        S.Action(1, "move_item", new GArray("inv", WoodSlot, "sto", 0));
        this.Check(((S.Count(Eng, "wood") == 0) && (GameSim.CountIn(S.Storage, "wood") == 20)), "wood moved into base storage at the chest");
        Eng.Pos = Gd.MakeVector2(0, (15 * 32));
        S.Action(1, "move_item", new GArray("sto", 0, "inv", 5));
        this.Check((GameSim.CountIn(S.Storage, "wood") == 20), "storage cannot be reached from outside the base");
        Eng.Pos = (GameSim.WORKBENCH_POS + Gd.MakeVector2(0, 24));
        S.Action(1, "move_item", new GArray("sto", 0, "inv", 5));
        this.Check((GameSim.CountIn(S.Storage, "wood") == 20), "nor from elsewhere in the base (the workbench is not the chest)");
        Eng.Pos = (GameSim.STORAGE_POS + Gd.MakeVector2(0, 24));
        S.Action(1, "move_item", new GArray("sto", 0, "inv", 5));
        this.Check(((S.Count(Eng, "wood") == 20) && (Gd.At(Gd.At(Eng.Inv, 5), 0) == "wood")), "and taken back into a chosen slot");
        S.Action(1, "move_item", new GArray("inv", 5, "inv", 0));
        this.Check(((Gd.At(Gd.At(Eng.Inv, 0), 0) == "wood") && (Gd.At(Gd.At(Eng.Inv, 5), 0) == "hammer")), "dragging onto a hotbar slot swaps the items");
        S.Action(1, "select", 1);
        this.Check((Eng.Sel == 1), "1-4 select the hotbar slot");
        // G gives the selected stack to a teammate in reach, otherwise drops it
        S.Action(1, "select", 0);
        Sc.Pos = (Eng.Pos + Gd.MakeVector2(32, 0));
        He.Pos = Gd.MakeVector2(0, (-15 * 32));
        S.Action(1, "give", 0);
        this.Check(((S.Count(Eng, "wood") == 0) && (S.Count(Sc, "wood") == 20)), "G gives the selected stack to the nearest teammate");
        Sc.Pos = Gd.MakeVector2(0, (-15 * 32));
        Eng.Pos = Gd.MakeVector2(0, (15 * 32));
        S.SetCount(Eng, "herb", 3);
        int HerbSlot = Gd.Int(Gd.Find(Gd.Map(Eng.Inv, (Func<dynamic, dynamic>)((X) => ((X != null) ? (dynamic)(Gd.At(X, 0)) : ""))), "herb"));
        S.Action(1, "move_item", new GArray("inv", HerbSlot, "inv", 3));
        S.Action(1, "select", 3);
        S.Action(1, "give", 0);
        this.Check(((S.Count(Eng, "herb") == 0) && Gd.Truth(Gd.Any(S.Drops, (Func<dynamic, dynamic>)((D) => ((D.Item == "herb") && Gd.Truth(D.Player)))))), "with nobody in reach G drops the stack");
        this.Run(S, 40.0f);
        this.Check((Gd.Size(S.Drops) == 1), "items dropped by players do not vanish");
        Eng.Inter = true;
        this.Run(S, 0.1f);
        Eng.Inter = false;
        this.Check(((S.Count(Eng, "herb") == 3) && Gd.Truth(Gd.IsEmpty(S.Drops))), "E picks a dropped item back up");
        // Crafting is a 3 s channel at the workbench; leaving cancels it (BAL-19)
        Eng.Pos = (GameSim.STORAGE_POS + Gd.MakeVector2(0, 24));
        S.SetCount(Eng, "herb", 2);
        this.Check(!Gd.Truth(S.CanCraft(Eng, 1, false)), "no crafting in the base away from the workbench");
        Eng.Pos = (GameSim.WORKBENCH_POS + Gd.MakeVector2(0, 24));
        S.Action(1, "craft", 1);
        this.Run(S, 1.0f);
        Eng.Pos = Gd.MakeVector2(0, (15 * 32));
        this.Run(S, 2.5f);
        this.Check(((S.Count(Eng, "bandage") == 0) && (S.Count(Eng, "herb") == 2) && (Eng.CraftIdx == (-1))), "leaving the workbench cancels a craft and keeps the materials");
        // Bow and arrows (MEC-03, BAL-10, BAL-42)
        S.Unlock = 1;
        Eng.Pos = (GameSim.WORKBENCH_POS + Gd.MakeVector2(0, 24));
        S.SetCount(Eng, "wood", 7);
        S.SetCount(Eng, "titanium", 2);
        S.Action(1, "craft", 6);
        this.Run(S, 3.1f);
        this.Check(((S.Count(Eng, "bow") == 1) && (S.Count(Eng, "arrow") == 5) && (S.Count(Eng, "wood") == 1)), "Bow + 5 arrows costs 6 wood + 2 titanium");
        S.Action(1, "craft", 7);
        this.Run(S, 3.1f);
        this.Check(((S.Count(Eng, "arrow") == 10) && (S.Count(Eng, "wood") == 0)), "5 arrows cost 1 wood");
        dynamic TheBow = Gd.At(Gd.Filter(Eng.Inv, (Func<dynamic, dynamic>)((X) => GameSim.IsBow(X))), 0);
        this.Check(((GameSim.Loaded(TheBow) == 10) && !Gd.Truth(Gd.Any(Eng.Inv, (Func<dynamic, dynamic>)((X) => ((X != null) && Gd.Equal(Gd.At(X, 0), "arrow")))))), "the bow holds its arrows: all 10 loaded, no slot spent on arrows");
        Gd.Clear(S.Nodes);
        S.World.Rebuild(S.Nodes, S.Towers);
        Eng.Pos = Gd.MakeVector2(0, (15 * 32));
        int BowSlot = Gd.Int(Gd.Find(Gd.Map(Eng.Inv, (Func<dynamic, dynamic>)((X) => ((X != null) ? (dynamic)(Gd.At(X, 0)) : ""))), "bow"));
        S.Action(1, "move_item", new GArray("inv", BowSlot, "inv", 2));
        S.Action(1, "select", 2);
        dynamic Target = S.Spawn(GameSim.GRUNT, 0, 0.0f);
        Target.Pos = (Eng.Pos + Gd.MakeVector2((7.5f * 32), 0));
        Target.Spd = 0.0f;
        Target.State = 4;
        Target.Home = Target.Pos;
        Target.Wander = Target.Pos;
        Target.Hp = 100.0f;
        Eng.Aim = 0.0f;
        Eng.Atk = true;
        this.Run(S, 0.05f);
        Eng.Atk = false;
        this.Run(S, 1.0f);
        this.Check(((Target.Hp == 88.0f) && (S.Count(Eng, "arrow") == 9)), Gd.Format("an arrow hits an enemy 7.5 tiles away for 12 and uses one arrow (hp %.1f)", Target.Hp));
        Target.Pos = (Eng.Pos + Gd.MakeVector2((9 * 32), 0));
        Target.Home = Target.Pos;
        Target.Wander = Target.Pos;
        Eng.Atk = true;
        this.Run(S, 0.05f);
        Eng.Atk = false;
        this.Run(S, 1.0f);
        this.Check((Target.Hp == 88.0f), "an arrow stops at its 8-tile range");
        S.SetCount(Eng, "arrow", 0);
        Eng.Atk = true;
        this.Run(S, 1.0f);
        Eng.Atk = false;
        this.Check(Gd.Truth(Gd.IsEmpty(S.Arrows)), "the crafted bow cannot fire without arrows");
        // loose arrows dragged onto the bow load into it, up to 30; the rest stays in its slot
        int Q1 = Gd.Int(Gd.Find(Eng.Inv, null));
        Eng.Inv[Q1] = new GArray("arrow", 20);
        int Q2 = Gd.Int(Gd.Find(Eng.Inv, null));
        Eng.Inv[Q2] = new GArray("arrow", 20);
        S.Action(1, "move_item", new GArray("inv", Q1, "inv", 2));
        S.Action(1, "move_item", new GArray("inv", Q2, "inv", 2));
        this.Check(((GameSim.Loaded(Gd.At(Eng.Inv, 2)) == 30) && (Gd.At(Eng.Inv, Q1) == null) && (Gd.Int(Gd.At(Gd.At(Eng.Inv, Q2), 1)) == 10)), "arrows dragged onto the bow load it up to 30, the rest stays in its slot");
        // a dropped bow drops its arrows beside it; picked up again they go back in
        S.Action(1, "give", null);
        this.Check(((S.Count(Eng, "bow") == 0) && (S.Count(Eng, "arrow") == 10) && Gd.Truth(Gd.Any(S.Drops, (Func<dynamic, dynamic>)((D) => (Gd.Equal(D.Item, "arrow") && (D.N == 30)))))), "dropping the bow drops its 30 arrows with it");
        S.PickUp(Eng);
        S.PickUp(Eng);
        dynamic Again = Gd.At(Gd.Filter(Eng.Inv, (Func<dynamic, dynamic>)((X) => GameSim.IsBow(X))), 0);
        this.Check(((Again != null) && (GameSim.Loaded(Again) == 30) && (S.Count(Eng, "arrow") == 40)), "picked up again, the bow is refilled from the bag first and the rest stays loose");
        S.SetCount(Eng, "arrow", 0);
        Sc.Pos = (Target.Pos - Gd.MakeVector2((7.5f * 32), 0));
        S.Action(2, "select", 0);
        Sc.Aim = 0.0f;
        Sc.Atk = true;
        this.Run(S, 0.05f);
        Sc.Atk = false;
        this.Run(S, 1.0f);
        this.Check((Target.Hp == 76.0f), Gd.Format("the Scout's starter bow needs no arrows and hits like the crafted bow (12 damage, 8 tiles; hp %.1f)", Target.Hp));
        // Walls (MEC-11, BAL-27)
        Gd.Clear(S.Enemies);
        Vector2 Door = (Vector2)(Gd.At(GameSim.DOOR_POS, 0));
        Vector2 Dir = (Vector2)(Gd.At(GameSim.DOOR_DIR, 0));
        Eng.Pos = (Door + ((Dir * 4) * 32));
        S.SetCount(Eng, "wood", 10);
        S.Action(1, "build", new GArray("wood", (Door + ((Dir * 2) * 32)), true));
        this.Check(((Gd.Size(S.BuiltWalls) == 0) && (S.Count(Eng, "wood") == 10)), "no wall within 3 tiles of a door");
        Vector2 Spot = GameSim.SnapToTile((Door + ((Dir * 6) * 32)));
        S.Action(1, "build", new GArray("wood", Spot, true));
        this.Check(((Gd.Size(S.BuiltWalls) == 1) && (Gd.At(S.BuiltWalls, 0).Hp == 200.0f) && (S.Count(Eng, "wood") == 5)), "a wood wall costs 5 wood and has 200 HP");
        S.SetCount(Eng, "stone", 5);
        S.Action(1, "build", new GArray("stone", (Spot + Gd.MakeVector2(0, (4 * 32))), true));
        this.Check((Gd.Size(S.BuiltWalls) == 2), "stone walls unlock after night 1");
        S.Action(2, "build", new GArray("wood", (Spot + Gd.MakeVector2(0, (-5 * 32))), true));
        this.Check((Gd.Size(S.BuiltWalls) == 2), "only the Engineer builds");
        S.World.Rebuild(S.Nodes, S.Towers, S.BuiltWalls);
        this.Check((S.World.Resolve(Spot, 10.0f) != Spot), "a wall blocks movement");
        dynamic Wg = S.Spawn(GameSim.GRUNT, 0, 0.0f);
        Wg.Pos = (Spot + (Dir * 32));
        // barely moving, so it stays pressed against the wall instead of walking around it
        Wg.Spd = 0.001f;
        S.Phase = "night";
        S.NextWave = float.PositiveInfinity;
        Eng.Pos = Gd.MakeVector2(0, (-30 * 32));
        Sc.Pos = Gd.MakeVector2(0, (-30 * 32));
        He.Pos = Gd.MakeVector2(0, (-30 * 32));
        this.Run(S, 3.5f);
        this.Check((Gd.At(S.BuiltWalls, 0).Hp < 200.0f), "an enemy stuck at a wall attacks it");
        Gd.At(S.BuiltWalls, 0).Hp = 5.0f;
        this.Run(S, 2.5f);
        this.Check((Gd.Size(S.BuiltWalls) == 1), "a wall at 0 HP is destroyed");
        // Revival kit: crafted into the bag, carried to the dead teammate and used there (hold E)
        S = this.NewMatch();
        dynamic Dead = Gd.At(S.Players, 2);
        Dead.State = 2;
        Dead.Pos = (Gd.At(GameSim.DOOR_POS, 2) + Gd.MakeVector2((10 * 32), 0));
        Vector2 Fell = (Vector2)Dead.Pos;
        dynamic Crafter = Gd.At(S.Players, 1);
        Crafter.Pos = (GameSim.WORKBENCH_POS + Gd.MakeVector2(0, 24));
        S.SetCount(Crafter, "herb", 4);
        S.SetCount(Crafter, "titanium", 4);
        S.Action(1, "craft", 2);
        this.Run(S, 3.1f);
        this.Check(((Dead.State == 2) && (S.Count(Crafter, "revive") == 1)), "a crafted Revival kit goes into the bag and revives nobody by itself");
        Crafter.Pos = (Fell + Gd.MakeVector2(24, 0));
        Crafter.Inter = true;
        this.Run(S, 1.0f);
        this.Check((Dead.State == 2), "using the kit takes a few seconds");
        this.Run(S, 2.2f);
        Crafter.Inter = false;
        this.Check(((Dead.State == 0) && (Dead.Hp == (0.5f * Dead.Maxhp)) && (((Vector2)Dead.Pos).DistanceTo(Fell) < 2.0f) && (S.Count(Crafter, "revive") == 0)), "the kit used on the body brings them back where they fell with 50% HP");
        // Result screen (section 2.5)
        S.BaseHp = 0.0f;
        S.LastDoor = 1;
        S.Phase = "night";
        this.Run(S, 0.1f);
        this.Check(((S.Phase == "result") && (Gd.At(S.Result, 1) == "Generator destroyed at door B")), ("a loss names its cause and door: " + Gd.Str(S.Result)));
        this.Run(S, 30.0f);
        this.Check((S.Phase == "result"), "the result screen stays until Back to lobby");
        S.Action(1, "lobby", 0);
        this.Check(((S.Phase == "lobby") && (S.Result == null)), "Back to lobby returns the team to the lobby");
    }
}
